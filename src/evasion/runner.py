"""Generation and handling of the self-extracting HBX1 runner.

A *runner* is the artifact the audit executes: a single file that carries an
encrypted HBX1 container, waits for the configured delay, recovers the
payload and launches it. Two flavours are produced:

``script`` mode
    A zipapp archive: a Python launcher plus the encrypted container, stored
    uncompressed so the file size is exactly predictable. The launcher only
    needs a Python 3 interpreter, because the AES-GCM implementation is
    spliced into it.

``executable`` mode
    The launcher and the container are packaged into one native executable
    with PyInstaller, which is what the audit needs on Windows (``.exe``).

The runner does not modify the system it runs on: it recovers the payload
into a temporary directory, launches it as a normal child process and removes
the temporary directory afterwards.
"""

from __future__ import annotations

import io
import os
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

from .constants import (
    MIB,
    RUNNER_CONTAINER_NAME,
    RUNNER_MAGIC,
)
from .container import parse_container
from .encoding import b64_encode
from ..embedding import build_executable as _package_executable
from ..embedding import pure_aes_source

# Marker block written at the very top of every generated launcher.
_MARKER_TEMPLATE = (
    "#!/usr/bin/env python3\n"
    "# {magic}\n"
    "# HBX-CONTAINER-NAME: {container_name}\n"
)

_CONTAINER_NAME_PATTERN = re.compile(
    rb"^# HBX-CONTAINER-NAME:\s*(\S+)\s*$", re.MULTILINE
)

# Name of the launcher inside the archive.
LAUNCHER_NAME = "__main__.py"

# Name of the padding member used for file-size manipulation.
PADDING_NAME = "padding.bin"

# Shebang prepended to the archive so it can be executed directly on POSIX.
SHEBANG = b"#!/usr/bin/env python3\n"

RUNNER_TEMPLATE = '''"""Hidden-Bytes self-extracting runner.

This file was generated by the Hidden-Bytes evasion tool. Running it waits for
the delay recorded in the container, decrypts the embedded payload with
AES-256-GCM using the randomly generated key embedded below and executes it.
"""

import base64
import json
import os
import runpy
import shutil
import struct
import subprocess
import sys
import tempfile
import time
import zipfile

MAGIC = b"HBX1"
CONTAINER_NAME = "{container_name}"
HBX_KEY = "{hbx_key}"

{pure_aes_source}

def _hbx_container_bytes():
    """Return the raw bytes of the embedded HBX1 container."""

    # In a frozen bundle the data files are unpacked next to the executable.
    bundle = getattr(sys, "_MEIPASS", None)
    if bundle is not None:
        candidate = os.path.join(bundle, CONTAINER_NAME)
        if os.path.isfile(candidate):
            with open(candidate, "rb") as handle:
                return handle.read()

    here = os.path.dirname(os.path.abspath(__file__))

    adjacent = os.path.join(here, CONTAINER_NAME)
    if os.path.isfile(adjacent):
        with open(adjacent, "rb") as handle:
            return handle.read()

    try:
        with zipfile.ZipFile(here) as archive:
            return archive.read(CONTAINER_NAME)
    except (OSError, KeyError, zipfile.BadZipFile) as exc:
        raise ValueError("unable to read the embedded container: " + str(exc))


def main():
    print("[INFO] Hidden-Bytes self-extracting runner.", flush=True)

    try:
        data = _hbx_container_bytes()
    except (OSError, ValueError) as exc:
        print("[ERROR] " + str(exc), file=sys.stderr)
        return 1

    if len(data) < 8 or data[:4] != MAGIC:
        print("[ERROR] embedded data is not a valid HBX1 container", file=sys.stderr)
        return 1

    header_length = struct.unpack(">I", data[4:8])[0]
    header = json.loads(data[8:8 + header_length].decode("utf-8"))
    ciphertext = data[8 + header_length:8 + header_length + int(header["ciphertext_length"])]

    delay = float(header.get("delay_seconds", 0))
    name = os.path.basename(header.get("original_name") or "payload.bin")

    key = base64.b64decode(HBX_KEY)

    if delay > 0:
        print("[INFO] Execution delayed by %g seconds..." % delay, flush=True)
        time.sleep(delay)

    nonce = base64.b64decode(header["nonce"])

    try:
        plaintext = decrypt_gcm(key, nonce, ciphertext, MAGIC)
    except InvalidTagError:
        print(
            "[ERROR] decryption failed: wrong key or damaged container",
            file=sys.stderr,
        )
        return 1

    if len(plaintext) != int(header["original_size"]):
        print("[ERROR] recovered payload size does not match the container", file=sys.stderr)
        return 1

    print("[INFO] Binary decrypted successfully.", flush=True)

    workdir = tempfile.mkdtemp(prefix="hbx_")
    try:
        target = os.path.join(workdir, name)

        with open(target, "wb") as output:
            output.write(plaintext)

        try:
            os.chmod(target, 0o700)
        except OSError:
            pass

        print("[INFO] Target program executed.", flush=True)

        if target.endswith((".py", ".pyw")):
            # In a frozen bundle sys.executable is the bundle itself, so a
            # Python payload is executed in-process instead of being spawned.
            if getattr(sys, "frozen", False):
                runpy.run_path(target, run_name="__main__")
                return 0
            command = [sys.executable, target]
        else:
            command = [target]

        return subprocess.run(command).returncode
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
'''


def _pure_aes_source() -> str:
    """Return the source of the dependency-free AES-GCM implementation."""

    return pure_aes_source()


def render_runner(
    container_name: str = RUNNER_CONTAINER_NAME, hbx_key: str = ""
) -> bytes:
    """Render the launcher of a runner.

    ``hbx_key`` is the Base64-encoded random AES-256 key embedded in the
    launcher so the runner can recover its payload without a passphrase.
    """

    source = RUNNER_TEMPLATE
    source = source.replace("{pure_aes_source}", _pure_aes_source(), 1)
    source = source.replace("{container_name}", container_name, 1)
    source = source.replace("{hbx_key}", hbx_key, 1)

    marker = _MARKER_TEMPLATE.format(
        magic=RUNNER_MAGIC.decode("ascii"),
        container_name=container_name,
    )

    launcher = (marker + source).encode("utf-8")

    # Guard against a malformed template: the launcher must be valid Python
    # before it is embedded in an artifact.
    compile(launcher.decode("utf-8"), "<runner>", "exec")

    return launcher


def _build_archive(
    launcher: bytes,
    container: bytes,
    padding: int,
) -> bytes:
    """Build the runner archive with an exactly known size.

    The container and the padding are stored uncompressed, so the archive
    size grows by exactly one byte per padding byte.
    """

    buffer = io.BytesIO()

    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(
            zipfile.ZipInfo(LAUNCHER_NAME),
            launcher,
            compress_type=zipfile.ZIP_DEFLATED,
        )
        archive.writestr(
            zipfile.ZipInfo(RUNNER_CONTAINER_NAME),
            container,
            compress_type=zipfile.ZIP_STORED,
        )
        if padding:
            archive.writestr(
                zipfile.ZipInfo(PADDING_NAME),
                os.urandom(padding),
                compress_type=zipfile.ZIP_STORED,
            )

    return SHEBANG + buffer.getvalue()


def is_runner(path: Path) -> bool:
    """Return True when the file is a Hidden-Bytes runner."""

    if not path.is_file():
        return False

    try:
        with path.open("rb") as handle:
            head = handle.read(4096)
    except OSError:
        return False

    if RUNNER_MAGIC in head:
        return True

    return _archive_container_name(path) is not None


def _archive_container_name(path: Path) -> str | None:
    """Return the container member name of a runner archive."""

    try:
        with zipfile.ZipFile(path) as archive:
            names = archive.namelist()
    except (OSError, zipfile.BadZipFile):
        return None

    for name in names:
        if name.endswith(RUNNER_CONTAINER_NAME):
            return name

    return None


def read_runner_container(path: Path) -> tuple[dict, bytes]:
    """Extract the HBX1 container embedded in a runner file."""

    if not path.is_file():
        raise ValueError(f"input file does not exist: {path}")

    with path.open("rb") as handle:
        head = handle.read(4096)

    match = _CONTAINER_NAME_PATTERN.search(head)
    if match is not None:
        member = match.group(1).decode("ascii")
        with zipfile.ZipFile(path) as archive:
            data = archive.read(member)
    else:
        member = _archive_container_name(path)
        if member is None:
            raise ValueError("file is not a recognised Hidden-Bytes runner")
        with zipfile.ZipFile(path) as archive:
            data = archive.read(member)

    return parse_container(data)


def read_runner_header(path: Path) -> dict:
    """Extract only the metadata header of the container in a runner."""

    header, _ciphertext = read_runner_container(path)
    return header


def plan_runner(
    source: Path,
    add_size_mb: float,
    delay: float,
) -> dict:
    """Compute the pieces of a runner: payload, padding and metadata."""

    from .crypto import build_payload

    body, header, key = build_payload(source, delay)

    launcher = render_runner(RUNNER_CONTAINER_NAME, b64_encode(key))
    archive = _build_archive(launcher, body, 0)

    requested_size = source.stat().st_size + round(add_size_mb * MIB)

    if requested_size < len(archive):
        raise ValueError(
            "requested final size is too small for the runner, its metadata "
            f"and ciphertext. Minimum required: {len(archive)} bytes; "
            f"requested: {requested_size} bytes."
        )

    return {
        "body": body,
        "header": header,
        "key": key,
        "padding": 0,
        "launcher": launcher,
        "archive_size": len(archive),
        "requested_size": requested_size,
    }


def build_runner_file(
    source: Path,
    output: Path,
    add_size_mb: float,
    delay: float,
) -> dict:
    """Create the self-extracting runner as a single executable file.

    The random encryption key is embedded in the runner so it can recover its
    payload without a passphrase, and a sidecar ``.key`` file is written next
    to the output so the container can also be recovered with ``--key``.
    """

    plan = plan_runner(source, add_size_mb, delay)

    # The padding member adds a fixed zip overhead on top of its own bytes.
    # The overhead is measured with a first build and corrected with a
    # second one, so the final file has exactly the requested size.
    base_size = plan["archive_size"]
    padding = plan["requested_size"] - base_size
    archive = _build_archive(plan["launcher"], plan["body"], padding)

    if len(archive) != plan["requested_size"]:
        overhead = len(archive) - base_size - padding
        padding = plan["requested_size"] - base_size - overhead
        archive = _build_archive(plan["launcher"], plan["body"], padding)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(archive)

    try:
        output.chmod(0o755)
    except OSError:
        pass

    # Sidecar key file for CLI-based recovery of the container.
    key_path = output.with_name(output.name + ".key")
    key_path.write_text(b64_encode(plan["key"]) + "\n", encoding="ascii")
    try:
        key_path.chmod(0o600)
    except OSError:
        pass
    plan["key_path"] = key_path

    plan["padding"] = padding
    plan["actual_size"] = len(archive)

    return plan


def write_launcher(
    output: Path,
    container_name: str = RUNNER_CONTAINER_NAME,
    hbx_key: str = "",
) -> bytes:
    """Write only the launcher part of a runner, without the container."""

    launcher = render_runner(container_name, hbx_key)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(launcher)
    return launcher


def build_executable(
    runner_path: Path,
    container_path: Path,
    output: Path,
    name: str,
    workdir: Path | None = None,
) -> Path:
    """Package a runner and its container into a single native executable.

    Requires PyInstaller. On Windows the result is a ``.exe`` file, which is
    what the audit demonstration needs.
    """

    owned_workdir = workdir is None
    if workdir is None:
        workdir = Path(tempfile.mkdtemp(prefix="hbx_build_"))

    try:
        return _package_executable(
            runner_path,
            output,
            name,
            extra_data=container_path,
            workdir=workdir,
        )
    finally:
        if owned_workdir:
            shutil.rmtree(workdir, ignore_errors=True)


def build_executable_from_source(
    source: Path,
    output: Path,
    add_size_mb: float,
    delay: float,
    workdir: Path | None = None,
) -> dict:
    """Build a self-extracting native executable from a payload file.

    The launcher and the encrypted container are packaged into a single
    executable with PyInstaller. The size padding is appended after the
    packaged archive: the PyInstaller loader locates the archive with a
    back-to-front scan for its cookie, so trailing bytes do not affect the
    execution of the executable. This makes the final size exact.

    The random encryption key is embedded in the launcher so the executable
    can recover its payload without a passphrase, and a sidecar ``.key`` file
    is written next to the output for CLI-based recovery.
    """

    from .crypto import build_payload

    owned_workdir = workdir is None
    if workdir is None:
        workdir = Path(tempfile.mkdtemp(prefix="hbx_build_"))

    try:
        name = output.stem or "runner"

        body, header, key = build_payload(source, delay)

        launcher_path = workdir / "runner_launcher.py"
        write_launcher(launcher_path, RUNNER_CONTAINER_NAME, b64_encode(key))

        container_path = workdir / RUNNER_CONTAINER_NAME
        container_path.write_bytes(body)

        built = workdir / "dist_out" / name
        if sys.platform == "win32":
            built = built.with_suffix(".exe")

        build_executable(
            launcher_path,
            container_path,
            built,
            name,
            workdir=workdir / "pyi",
        )

        base_size = built.stat().st_size
        target_size = source.stat().st_size + round(add_size_mb * MIB)

        if target_size < base_size:
            raise ValueError(
                "requested final size is too small for the packaged "
                "executable: the bundled Python runtime already needs "
                f"{base_size} bytes. Use a larger --add-size value."
            )

        padding = target_size - base_size
        if padding:
            with built.open("ab") as handle:
                remaining = padding
                while remaining:
                    chunk = min(remaining, MIB)
                    handle.write(os.urandom(chunk))
                    remaining -= chunk

        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(built, output)

        # Sidecar key file for CLI-based recovery of the container.
        key_path = output.with_name(output.name + ".key")
        key_path.write_text(b64_encode(key) + "\n", encoding="ascii")
        try:
            key_path.chmod(0o600)
        except OSError:
            pass

        return {
            "header": header,
            "key": key,
            "key_path": key_path,
            "padding": padding,
            "overhead": base_size,
            "target_size": target_size,
            "actual_size": output.stat().st_size,
        }
    finally:
        if owned_workdir:
            shutil.rmtree(workdir, ignore_errors=True)
