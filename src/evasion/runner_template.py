def _hbx_container_bytes():
    """Return the raw bytes of the embedded HBX1 container."""

    # In a frozen bundle the data files are unpacked next to the executable.
    bundle = getattr(sys, "_MEIPASS", None)
    if bundle is not None:
        candidate = os.path.join(bundle, CONTAINER_NAME)
        if os.path.isfile(candidate):
            with open(candidate, "rb") as handle:
                return handle.read()

    here = os.path.dirname(os.path.abspath(__file__))

    adjacent = os.path.join(here, CONTAINER_NAME)
    if os.path.isfile(adjacent):
        with open(adjacent, "rb") as handle:
            return handle.read()

    try:
        with zipfile.ZipFile(here) as archive:
            return archive.read(CONTAINER_NAME)
    except (OSError, KeyError, zipfile.BadZipFile) as exc:
        raise ValueError("unable to read the embedded container: " + str(exc))


