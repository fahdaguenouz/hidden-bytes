def _pure_aes_source() -> str:
    """Return the source of the dependency-free AES-GCM implementation."""

    try:
        from importlib.resources import files

        source = (
            files("hidden_bytes.evasion")
            .joinpath("pure_aes.py")
            .read_text(encoding="utf-8")
        )
    except Exception:  # noqa: BLE001 - fall back to the package directory
        source = Path(__file__).with_name("pure_aes.py").read_text(encoding="utf-8")

    return source


def render_runner(container_name: str = RUNNER_CONTAINER_NAME) -> bytes:
    """Render the launcher of a runner."""

    source = RUNNER_TEMPLATE
    source = source.replace("{pure_aes_source}", _pure_aes_source(), 1)
    source = source.replace("{container_name}", container_name, 1)

    marker = _MARKER_TEMPLATE.format(
        magic=RUNNER_MAGIC.decode("ascii"),
        container_name=container_name,
    )

    launcher = (marker + source).encode("utf-8")

    # Guard against a malformed template: the launcher must be valid Python
    # before it is embedded in an artifact.
    compile(launcher.decode("utf-8"), "<runner>", "exec")

    return launcher


def _build_archive(
    launcher: bytes,
    container: bytes,
    padding: int,
) -> bytes:
    """Build the runner archive with an exactly known size.

    The container and the padding are stored uncompressed, so the archive
    size grows by exactly one byte per padding byte.
    """

    buffer = io.BytesIO()

    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(
            zipfile.ZipInfo(LAUNCHER_NAME),
            launcher,
            compress_type=zipfile.ZIP_DEFLATED,
        )
        archive.writestr(
            zipfile.ZipInfo(RUNNER_CONTAINER_NAME),
            container,
            compress_type=zipfile.ZIP_STORED,
        )
        if padding:
            archive.writestr(
                zipfile.ZipInfo(PADDING_NAME),
                os.urandom(padding),
                compress_type=zipfile.ZIP_STORED,
            )

    return SHEBANG + buffer.getvalue()


def is_runner(path: Path) -> bool:
    """Return True when the file is a Hidden-Bytes runner."""

    if not path.is_file():
        return False

    try:
        with path.open("rb") as handle:
            head = handle.read(4096)
    except OSError:
        return False

    if RUNNER_MAGIC in head:
        return True

    return _archive_container_name(path) is not None


def _archive_container_name(path: Path) -> str | None:
    """Return the container member name of a runner archive."""

    try:
        with zipfile.ZipFile(path) as archive:
            names = archive.namelist()
    except (OSError, zipfile.BadZipFile):
        return None

    for name in names:
        if name.endswith(RUNNER_CONTAINER_NAME):
            return name

    return None


def read_runner_container(path: Path) -> tuple[dict, bytes]:
    """Extract the HBX1 container embedded in a runner file."""

    if not path.is_file():
        raise ValueError(f"input file does not exist: {path}")

    with path.open("rb") as handle:
        head = handle.read(4096)

    match = _CONTAINER_NAME_PATTERN.search(head)
    if match is not None:
        member = match.group(1).decode("ascii")
        with zipfile.ZipFile(path) as archive:
            data = archive.read(member)
    else:
        member = _archive_container_name(path)
        if member is None:
            raise ValueError("file is not a recognised Hidden-Bytes runner")
        with zipfile.ZipFile(path) as archive:
            data = archive.read(member)

    return parse_container(data)


def read_runner_header(path: Path) -> dict:
    """Extract only the metadata header of the container in a runner."""

    header, _ciphertext = read_runner_container(path)
    return header


def plan_runner(
    source: Path,
    add_size_mb: float,
    delay: float,
    passphrase: str | None = None,
    passphrase_source: dict | None = None,
) -> dict:
    """Compute the pieces of a runner: payload, padding and metadata."""

    from .crypto import build_payload

    body, header, key = build_payload(
        source, delay, passphrase, passphrase_source
    )

    launcher = render_runner()
    archive = _build_archive(launcher, body, 0)

    requested_size = source.stat().st_size + round(add_size_mb * MIB)

    if requested_size < len(archive):
        raise ValueError(
            "requested final size is too small for the runner, its metadata "
            f"and ciphertext. Minimum required: {len(archive)} bytes; "
            f"requested: {requested_size} bytes."
        )

    return {
        "body": body,
        "header": header,
        "key": key,
        "padding": 0,
        "launcher": launcher,
        "archive_size": len(archive),
        "requested_size": requested_size,
    }


def build_runner_file(
    source: Path,
    output: Path,
    add_size_mb: float,
    delay: float,
    passphrase: str | None = None,
    passphrase_source: dict | None = None,
) -> dict:
    """Create the self-extracting runner as a single executable file."""

    plan = plan_runner(source, add_size_mb, delay, passphrase, passphrase_source)

    # The padding member adds a fixed zip overhead on top of its own bytes.
    # The overhead is measured with a first build and corrected with a
    # second one, so the final file has exactly the requested size.
    base_size = plan["archive_size"]
    padding = plan["requested_size"] - base_size
    archive = _build_archive(plan["launcher"], plan["body"], padding)

    if len(archive) != plan["requested_size"]:
        overhead = len(archive) - base_size - padding
        padding = plan["requested_size"] - base_size - overhead
        archive = _build_archive(plan["launcher"], plan["body"], padding)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(archive)

    try:
        output.chmod(0o755)
    except OSError:
        pass

    plan["padding"] = padding
    plan["actual_size"] = len(archive)

    return plan


def write_launcher(
    output: Path,
    container_name: str = RUNNER_CONTAINER_NAME,
) -> bytes:
    """Write only the launcher part of a runner, without the container."""

    launcher = render_runner(container_name)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(launcher)
    return launcher


def build_executable(
    runner_path: Path,
    container_path: Path,
    output: Path,
    name: str,
    workdir: Path | None = None,
    clean: bool = True,
) -> Path:
    """Package a runner and its container into a single native executable.

    Requires PyInstaller. On Windows the result is a ``.exe`` file, which is
    what the audit demonstration needs.
    """

    if shutil.which("pyinstaller") is None and not _has_pyinstaller_module():
        raise ValueError(
            "PyInstaller is not available. Install it with: "
            "python -m pip install pyinstaller"
        )

    owned_workdir = workdir is None
    if workdir is None:
        workdir = Path(tempfile.mkdtemp(prefix="hbx_build_"))

    try:
        container_path = container_path.resolve()
        runner_path = runner_path.resolve()

        command = [
            sys.executable,
            "-m",
            "PyInstaller",
            "--onefile",
            "--noconfirm",
            "--name",
            name,
            "--add-data",
            f"{container_path}{os.pathsep}.",
            "--distpath",
            str(workdir / "dist"),
            "--workpath",
            str(workdir / "build"),
            "--specpath",
            str(workdir),
            str(runner_path),
        ]

        if clean:
            command.insert(4, "--clean")

        completed = subprocess.run(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )

        if completed.returncode != 0:
            raise ValueError(
                "PyInstaller failed with exit code "
                f"{completed.returncode}:\n{completed.stdout}"
            )

        built = workdir / "dist" / name
        if sys.platform == "win32":
            built = built.with_suffix(".exe")

        if not built.is_file():
            raise ValueError("PyInstaller did not produce the expected executable")

        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(built, output)

        return output
    finally:
        if owned_workdir:
            shutil.rmtree(workdir, ignore_errors=True)


def build_executable_from_source(
    source: Path,
    output: Path,
    add_size_mb: float,
    delay: float,
    passphrase: str | None = None,
    passphrase_source: dict | None = None,
    workdir: Path | None = None,
) -> dict:
    """Build a self-extracting native executable from a payload file.

    The launcher and the encrypted container are packaged into a single
    executable with PyInstaller. The size padding is appended after the
    packaged archive: the PyInstaller loader locates the archive with a
    back-to-front scan for its cookie, so trailing bytes do not affect the
    execution of the executable. This makes the final size exact.
    """

    from .crypto import build_payload

    owned_workdir = workdir is None
    if workdir is None:
        workdir = Path(tempfile.mkdtemp(prefix="hbx_build_"))

    try:
        name = output.stem or "runner"

        body, header, key = build_payload(
            source, delay, passphrase, passphrase_source
        )

        launcher_path = workdir / "runner_launcher.py"
        write_launcher(launcher_path)

        container_path = workdir / RUNNER_CONTAINER_NAME
        container_path.write_bytes(body)

        built = workdir / "dist_out" / name
        if sys.platform == "win32":
            built = built.with_suffix(".exe")

        build_executable(
            launcher_path,
            container_path,
            built,
            name,
            workdir=workdir / "pyi",
        )

        base_size = built.stat().st_size
        target_size = source.stat().st_size + round(add_size_mb * MIB)

        if target_size < base_size:
            raise ValueError(
                "requested final size is too small for the packaged "
                "executable: the bundled Python runtime already needs "
                f"{base_size} bytes. Use a larger --add-size value."
            )

        padding = target_size - base_size
        if padding:
            with built.open("ab") as handle:
                remaining = padding
                while remaining:
                    chunk = min(remaining, MIB)
                    handle.write(os.urandom(chunk))
                    remaining -= chunk

        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(built, output)

        return {
            "header": header,
            "key": key,
            "padding": padding,
            "overhead": base_size,
            "target_size": target_size,
            "actual_size": output.stat().st_size,
        }
    finally:
        if owned_workdir:
            shutil.rmtree(workdir, ignore_errors=True)



def _has_pyinstaller_module() -> bool:
    """Return True when the PyInstaller module can be imported."""

    from importlib.util import find_spec

    try:
        return find_spec("PyInstaller") is not None
    except (ImportError, ValueError):  # pragma: no cover - defensive
        return False
